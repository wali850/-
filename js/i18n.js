export function setLang(l, save = true) {
  lang = (l in T) ? l : 'en';
  if (save) {
    try { localStorage.setItem('gb.lang', lang); } catch {}
  }
  document.documentElement.lang = lang;
  document.documentElement.dir = (lang === 'ps' || lang === 'fa') ? 'rtl' : 'ltr';
  applyStatic();
  listeners.forEach((fn) => fn());
}
